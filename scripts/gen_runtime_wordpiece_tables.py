"""Write ``playground/src/runtime/wordpiece-tables.ts`` from the Hugging Face ``tokenizers`` crate.

The browser's WordPiece tokenizer (``wordpiece.ts``) must classify every code point exactly like
the Rust ``BertNormalizer`` / ``BertPreTokenizer`` the Python reference runs, and the crate's
Unicode tables are not JavaScript's (it still uses an older ``unicode_categories``: unassigned
code points are kept, code points added to ``Cf``/``Mn`` after that version are not dropped). The
sets are therefore read off the real tokenizer of a bundle, one probe per code point:

- ``drop``: ``normalize_str(ch) == ""`` (control, format, private use, non-spacing marks);
- ``space``: ``normalize_str(ch) == " "`` (white space and the characters it maps to a space);
- ``cjk``: ``normalize_str(ch)`` is the character padded with spaces (``handle_chinese_chars``);
- ``punct``: ``pre_tokenize_str("a" + ch + "b")`` isolates ``ch`` (ASCII punctuation or symbol,
  Unicode ``P*``).

NFD and lowercase are not tabulated: ``String.prototype.normalize`` and ``toLowerCase`` agree with
the crate, which ``pnpm -C playground parity:en`` (every code point of the sweep) checks.

    uv run python scripts/gen_runtime_wordpiece_tables.py [--tokenizer PATH/tokenizer.json]
"""

from __future__ import annotations

import argparse
from importlib import metadata
from pathlib import Path

from tokenizers import Tokenizer

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_TOKENIZER = ROOT / "models" / "gidi-en-v4-bundle" / "tokenizer.json"
OUTPUT = ROOT / "playground" / "src" / "runtime" / "wordpiece-tables.ts"
MAX_CODE_POINT = 0x10FFFF
SURROGATES = range(0xD800, 0xE000)


def to_ranges(members: list[int]) -> list[int]:
    """Inclusive ``[start, end]`` ranges of the sorted code points, flat."""
    flat: list[int] = []
    for cp in members:
        if flat and flat[-1] == cp - 1:
            flat[-1] = cp
        else:
            flat += [cp, cp]
    return flat


def classify(tokenizer: Tokenizer) -> dict[str, list[int]]:
    normalizer = tokenizer.normalizer
    pre_tokenizer = tokenizer.pre_tokenizer
    sets: dict[str, list[int]] = {"drop": [], "space": [], "cjk": [], "punct": []}
    for cp in range(MAX_CODE_POINT + 1):
        if cp in SURROGATES:
            continue
        ch = chr(cp)
        out = normalizer.normalize_str(ch)
        if out == "":
            sets["drop"].append(cp)
        elif out == " ":
            sets["space"].append(cp)
        elif len(out) >= 3 and out[0] == " " and out[-1] == " ":
            sets["cjk"].append(cp)
        elif len(pre_tokenizer.pre_tokenize_str(f"a{ch}b")) == 3:
            sets["punct"].append(cp)
    return sets


DOC = {
    "drop": "`BertNormalizer` removes these (control, format, private use, non-spacing marks).",
    "space": "`BertNormalizer` turns these into a space; the pre-tokenizer splits on it.",
    "cjk": "`handle_chinese_chars` pads these with spaces: each is a word of its own.",
    "punct": "`BertPreTokenizer` makes each of these a word of its own.",
}


def render(sets: dict[str, list[int]]) -> str:
    version = metadata.version("tokenizers")
    lines = [
        f"// Generated by scripts/gen_runtime_wordpiece_tables.py from tokenizers {version}. "
        "Do not edit.",
        "// Flat inclusive [start, end] code point ranges.",
        "",
    ]
    for name, members in sets.items():
        flat = to_ranges(members)
        lines.append(f"/** {DOC[name]} ({len(members)} code points) */")
        lines.append(f"export const WP_{name.upper()}_RANGES: readonly number[] = [")
        lines += [f"  0x{flat[i]:X}, 0x{flat[i + 1]:X}," for i in range(0, len(flat), 2)]
        lines += ["]", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--tokenizer", type=Path, default=DEFAULT_TOKENIZER)
    args = parser.parse_args()
    sets = classify(Tokenizer.from_file(str(args.tokenizer)))
    OUTPUT.write_text(render(sets), encoding="utf-8")
    print(
        f"wrote {OUTPUT.relative_to(ROOT)}: " + ", ".join(f"{k} {len(v)}" for k, v in sets.items())
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
