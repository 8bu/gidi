#!/usr/bin/env python3
"""Compare value-span-v2-direction-repair with value-span-v1 and the frozen v1 baseline.

Reads only the per-seed prediction files and ``comparison.json`` written by
``scripts/compare_value_v1.py`` for both experiments; scores nothing new.

Usage:
    uv run python scripts/compare_direction_repair.py
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from gidi.corpus.jsonl import read_jsonl

PREV = Path("experiments/value-span-v1")
REPAIR = Path("experiments/value-span-v2-direction-repair")
SEEDS = (1, 2, 3)
SETS = ("test-v1", "probe")
WATCH = "ck cho Vũ mượn 700k"
TYPES = (
    "expense",
    "income",
    "borrow",
    "lend",
    "repayment_in",
    "repayment_out",
    "transfer",
    "refund",
)


def preds(exp: Path, prefix: str, seed: int, name: str) -> dict[str, dict[str, Any]]:
    return {
        r["id"]: r
        for r in read_jsonl(exp / "eval" / f"{prefix}seed{seed}-{name}-predictions.jsonl")
    }


def target_ok(r: dict[str, Any]) -> bool:
    return bool(r["target_ok"])


def build(prev: Path, repair: Path) -> dict[str, Any]:
    models = {"v1": (prev, "v1-"), "value-span-v1": (prev, ""), "repair": (repair, "")}
    data = {
        m: {s: {n: preds(e, p, s, n) for n in SETS} for s in SEEDS} for m, (e, p) in models.items()
    }
    out: dict[str, Any] = {"headline": {}, "per_gold_type": {}, "type_changes_vs_value_span_v1": {}}
    for name in SETS:
        head: dict[str, Any] = {}
        for m in models:
            rows = {s: list(data[m][s][name].values()) for s in SEEDS}
            head[m] = {
                "type_correct": {s: sum(r["type_ok"] for r in rows[s]) for s in SEEDS},
                "target_correct": {s: sum(target_ok(r) for r in rows[s]) for s in SEEDS},
                "joint_correct": {
                    s: sum(r["type_ok"] and target_ok(r) for r in rows[s]) for s in SEEDS
                },
            }
        out["headline"][name] = head
        per_type: dict[str, Any] = {}
        for t in TYPES:
            n = sum(r["gold_type"] == t for r in data["v1"][1][name].values())
            if not n:
                continue
            per_type[t] = {"n": n} | {
                m: [
                    sum(r["type_ok"] for r in data[m][s][name].values() if r["gold_type"] == t)
                    for s in SEEDS
                ]
                for m in models
            }
        out["per_gold_type"][name] = per_type
        changes: dict[str, Any] = {}
        for s in SEEDS:
            a, b = data["value-span-v1"][s][name], data["repair"][s][name]

            def change(i: str, a=a, b=b) -> str:
                old, new = a[i]["pred_type"], b[i]["pred_type"]
                return f"{b[i]['text']} ({old} -> {new}, gold {b[i]['gold_type']})"

            fixed = [change(i) for i in b if b[i]["type_ok"] and not a[i]["type_ok"]]
            broken = [change(i) for i in b if a[i]["type_ok"] and not b[i]["type_ok"]]
            changes[s] = {"fixed": fixed, "broken": broken}
        out["type_changes_vs_value_span_v1"][name] = changes
    watch = {}
    for m in models:
        for s in SEEDS:
            for r in data[m][s]["test-v1"].values():
                if r["text"] == WATCH:
                    watch.setdefault(m, {})[s] = r["pred_type"]
    out["watch_note"] = {"text": WATCH, "gold": "lend", "pred_type": watch}
    lf = {}
    for m, path in (("value-span-v1", prev), ("repair", repair)):
        table = json.loads((path / "comparison.json").read_text())["regression_table"]["probe"][
            "lender_first"
        ]
        lf["v1"] = table["type_correct"]["v1_per_seed"]
        lf[m] = table["type_correct"]["v2_per_seed"]
        lf["n"] = table["n"]
    out["probe_lender_first_type_correct"] = lf
    return out


def render(rep: dict[str, Any]) -> str:
    L = ["# value-span-v2-direction-repair vs value-span-v1 vs gidi-finance-v1", ""]
    L += [
        "Correct notes per seed (1 / 2 / 3). Generated by `scripts/compare_direction_repair.py`.",
        "",
    ]
    for name, head in rep["headline"].items():
        L += [
            f"## {name}",
            "",
            "| model | type | target exact | type+target joint |",
            "|---|---|---|---|",
        ]
        for m, h in head.items():
            cells = [
                " / ".join(str(h[k][s]) for s in SEEDS)
                for k in ("type_correct", "target_correct", "joint_correct")
            ]
            L.append(f"| {m} | " + " | ".join(cells) + " |")
        L += [
            "",
            "Type correct by gold type (seeds 1 / 2 / 3):",
            "",
            "| gold | n | v1 | value-span-v1 | repair |",
            "|---|---|---|---|---|",
        ]
        for t, d in rep["per_gold_type"][name].items():
            L.append(
                f"| {t} | {d['n']} | "
                + " | ".join(" / ".join(map(str, d[m])) for m in ("v1", "value-span-v1", "repair"))
                + " |"
            )
        L += ["", "Type changes, repair vs value-span-v1 (same seed):", ""]
        for s, c in rep["type_changes_vs_value_span_v1"][name].items():
            L.append(f"- seed {s}: fixed {len(c['fixed'])}, broken {len(c['broken'])}")
            L += [f"  - fixed: `{x}`" for x in c["fixed"]]
            L += [f"  - broken: `{x}`" for x in c["broken"]]
        L.append("")
    w = rep["watch_note"]
    L += [f"## `{w['text']}` (gold {w['gold']})", ""]
    for m, p in w["pred_type"].items():
        L.append(f"- {m}: " + ", ".join(f"seed {s} {t}" for s, t in p.items()))
    lf = rep["probe_lender_first_type_correct"]
    L += ["", f"## Probe lender-first slice type correct (n = {lf['n']})", ""]
    for m in ("v1", "value-span-v1", "repair"):
        L.append(f"- {m}: " + " / ".join(str(lf[m][str(s)]) for s in SEEDS))
    L.append("")
    return "\n".join(L)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--prev", type=Path, default=PREV)
    parser.add_argument("--repair", type=Path, default=REPAIR)
    args = parser.parse_args(argv)
    rep = build(args.prev, args.repair)
    (args.repair / "vs-value-span-v1.json").write_text(
        json.dumps(rep, indent=2, ensure_ascii=False) + "\n"
    )
    (args.repair / "vs-value-span-v1.md").write_text(render(rep))
    print(render(rep))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
