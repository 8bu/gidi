/**
 * Uncased BERT WordPiece tokenizer for the bundle's `tokenizer.json` (`gidi-en-v4`, MiniLM).
 * Port of the Hugging Face `tokenizers` crate configured as `BertNormalizer(clean_text,
 * handle_chinese_chars, lowercase)` + `BertPreTokenizer` + `WordPiece` + `[CLS] A [SEP]`:
 *
 * - added special tokens (`[PAD]`, `[UNK]`, `[CLS]`, `[SEP]`, `[MASK]`) are matched literally in
 *   the text first (leftmost-longest) and bypass the normalizer;
 * - normalizer, per piece of text between them: drop control, format and private-use characters,
 *   NUL, U+FFFD, map every white-space character to a space, pad CJK ideographs with spaces,
 *   decompose (NFD) and drop the non-spacing marks, lowercase. Every normalized character
 *   remembers the original code points it came from;
 * - pre-tokenizer: split on white space (dropped), every punctuation character (ASCII punctuation
 *   and symbols, Unicode `P*`) is a word of its own;
 *
 * Which code points are dropped, white space, CJK or punctuation is tabulated from the Rust crate
 * itself (`wordpiece-tables.ts`, generated by `scripts/gen_runtime_wordpiece_tables.py`): its
 * Unicode data is older than JavaScript's. NFD and lowercase use the JavaScript built-ins.
 * - WordPiece: greedy longest match from the left, continuation pieces take the `##` prefix; a
 *   word that does not decompose completely (or has more than `max_input_chars_per_word`
 *   characters) becomes one `[UNK]` covering the whole word;
 * - `[CLS]`/`[SEP]` around the pieces and right-side truncation to `maxLength` incl. both.
 *
 * Offsets are code points of the string given (the caller applies NFC). The offsets of a piece
 * are the min start and max end of the original characters of its normalized characters, which
 * is what the Rust `NormalizedString::convert_offsets` returns.
 */

import { inRanges, toCodePoints } from "./text.ts"
import type { BundleTokenizer, TokenizedText } from "./tokenizer.ts"
import {
  WP_CJK_RANGES,
  WP_DROP_RANGES,
  WP_PUNCT_RANGES,
  WP_SPACE_RANGES,
} from "./wordpiece-tables.ts"

interface AddedToken {
  id: number
  content: string
  cps: number[]
}

interface WordPieceJson {
  added_tokens: {
    id: number
    content: string
    special: boolean
    lstrip: boolean
    rstrip: boolean
    single_word: boolean
    normalized: boolean
  }[]
  normalizer: {
    type: string
    clean_text: boolean
    handle_chinese_chars: boolean
    strip_accents: boolean | null
    lowercase: boolean
  } | null
  pre_tokenizer: { type: string } | null
  post_processor: {
    type: string
    single: ({ SpecialToken: { id: string } } | { Sequence: { id: string } })[]
    special_tokens: Record<string, { ids: number[] }>
  }
  model: {
    type: string
    unk_token: string
    continuing_subword_prefix: string
    max_input_chars_per_word: number
    vocab: Record<string, number>
  }
}

/** One normalized character and the original code points `[start, end)` it came from. */
interface NChar {
  cp: number
  start: number
  end: number
}

const isDropped = (cp: number): boolean => inRanges(WP_DROP_RANGES, cp)
const isSpace = (cp: number): boolean => inRanges(WP_SPACE_RANGES, cp)
const isChineseChar = (cp: number): boolean => inRanges(WP_CJK_RANGES, cp)
const isBertPunctuation = (cp: number): boolean => inRanges(WP_PUNCT_RANGES, cp)

/** NFD, drop non-spacing marks, lowercase: the code points one kept character turns into. */
const FOLDED = new Map<number, number[]>()
function foldCodePoint(cp: number): number[] {
  if (cp < 0x80) return [cp >= 0x41 && cp <= 0x5a ? cp + 0x20 : cp]
  let folded = FOLDED.get(cp)
  if (folded === undefined) {
    folded = []
    for (const part of String.fromCodePoint(cp).normalize("NFD")) {
      if (isDropped(part.codePointAt(0) as number)) continue
      for (const lower of part.toLowerCase())
        folded.push(lower.codePointAt(0) as number)
    }
    FOLDED.set(cp, folded)
  }
  return folded
}

const SPACE = 0x20

export class WordPieceTokenizer implements BundleTokenizer {
  readonly maxLength: number
  private readonly vocab: Map<string, number>
  private readonly unkId: number
  private readonly prefix: string
  private readonly maxWordChars: number
  private readonly added: AddedToken[]
  private readonly clsId: number
  private readonly sepId: number

  constructor(tokenizerJson: unknown, maxLength: number) {
    const tj = tokenizerJson as WordPieceJson
    this.maxLength = maxLength
    WordPieceTokenizer.assertSupported(tj)
    this.vocab = new Map(Object.entries(tj.model.vocab))
    const unk = this.vocab.get(tj.model.unk_token)
    if (unk === undefined)
      throw new Error("tokenizer.json: unk_token not in vocab")
    this.unkId = unk
    this.prefix = tj.model.continuing_subword_prefix
    this.maxWordChars = tj.model.max_input_chars_per_word
    this.added = tj.added_tokens
      .map((t) => ({
        id: t.id,
        content: t.content,
        cps: toCodePoints(t.content),
      }))
      .sort((x, y) => y.cps.length - x.cps.length)
    const specials = tj.post_processor.special_tokens
    const [cls, sep] = tj.post_processor.single.flatMap((item) =>
      "SpecialToken" in item ? [specials[item.SpecialToken.id].ids[0]] : []
    )
    this.clsId = cls
    this.sepId = sep
  }

  private static assertSupported(tj: WordPieceJson): void {
    const template = tj.post_processor?.single?.map((i) =>
      "SpecialToken" in i ? "S" : "Sequence" in i ? "A" : "?"
    )
    const normalizer = tj.normalizer
    const unsupported =
      tj.model?.type !== "WordPiece" ||
      normalizer?.type !== "BertNormalizer" ||
      !normalizer.clean_text ||
      !normalizer.handle_chinese_chars ||
      !normalizer.lowercase ||
      normalizer.strip_accents !== null ||
      tj.pre_tokenizer?.type !== "BertPreTokenizer" ||
      tj.added_tokens.some(
        (t) => t.lstrip || t.rstrip || t.single_word || t.normalized
      ) ||
      template?.join("") !== "SAS"
    if (unsupported)
      throw new Error(
        "tokenizer.json: configuration not supported by this port"
      )
  }

  encode(cps: readonly number[]): TokenizedText {
    // A lone surrogate becomes U+FFFD (also one code point, so offsets stay aligned); the
    // normalizer then drops it.
    const text = cps.map((cp) => (cp >= 0xd800 && cp <= 0xdfff ? 0xfffd : cp))
    const budget = this.maxLength - 2
    const ids: number[] = []
    const offsets: [number, number][] = []

    const push = (id: number, start: number, end: number): boolean => {
      if (ids.length >= budget) return false
      ids.push(id)
      offsets.push([start, end])
      return true
    }

    let segmentStart = 0
    let ok = true
    const flushSegment = (segmentEnd: number): boolean => {
      for (const word of this.words(text, segmentStart, segmentEnd)) {
        for (const [id, start, end] of this.pieces(word)) {
          if (!push(id, start, end)) return false
        }
      }
      return true
    }

    let i = 0
    while (i < text.length && ok) {
      const match = this.addedTokenAt(text, i)
      if (match === null) {
        i++
        continue
      }
      ok = flushSegment(i) && push(match.id, i, i + match.cps.length)
      i += match.cps.length
      segmentStart = i
    }
    if (ok) ok = flushSegment(text.length)

    return {
      ids: [this.clsId, ...ids, this.sepId],
      offsets: [[0, 0], ...offsets, [0, 0]],
      specialTokensMask: [1, ...ids.map(() => 0), 1],
      truncated: !ok,
    }
  }

  private addedTokenAt(text: readonly number[], at: number): AddedToken | null {
    outer: for (const token of this.added) {
      if (at + token.cps.length > text.length) continue
      for (let k = 0; k < token.cps.length; k++) {
        if (text[at + k] !== token.cps[k]) continue outer
      }
      return token
    }
    return null
  }

  /** Normalizer + pre-tokenizer of `text[from, to)`: the words as normalized characters. */
  private words(text: readonly number[], from: number, to: number): NChar[][] {
    const words: NChar[][] = []
    let word: NChar[] = []
    const endWord = (): void => {
      if (word.length > 0) words.push(word)
      word = []
    }
    for (let at = from; at < to; at++) {
      const cp = text[at]
      if (isDropped(cp)) continue
      const spaced = isSpace(cp)
      const chinese = !spaced && isChineseChar(cp)
      if (spaced) {
        endWord()
        continue
      }
      if (chinese) endWord()
      for (const folded of foldCodePoint(cp)) {
        if (folded === SPACE) {
          endWord()
        } else if (isBertPunctuation(folded) || chinese) {
          endWord()
          words.push([{ cp: folded, start: at, end: at + 1 }])
        } else {
          word.push({ cp: folded, start: at, end: at + 1 })
        }
      }
      if (chinese) endWord()
    }
    endWord()
    return words
  }

  /** WordPiece of one word: `[id, start, end)` per piece, or one `[UNK]` over the whole word. */
  private pieces(word: readonly NChar[]): [number, number, number][] {
    let lo = Infinity
    let hi = -Infinity
    for (const c of word) {
      lo = Math.min(lo, c.start)
      hi = Math.max(hi, c.end)
    }
    if (word.length > this.maxWordChars) return [[this.unkId, lo, hi]]
    const out: [number, number, number][] = []
    let start = 0
    while (start < word.length) {
      let end = word.length
      let found: [number, number] | null = null
      while (start < end) {
        let piece = String.fromCodePoint(
          ...word.slice(start, end).map((c) => c.cp)
        )
        if (start > 0) piece = this.prefix + piece
        const id = this.vocab.get(piece)
        if (id !== undefined) {
          found = [id, end]
          break
        }
        end--
      }
      if (found === null) return [[this.unkId, lo, hi]]
      let s = Infinity
      let e = -Infinity
      for (let k = start; k < found[1]; k++) {
        s = Math.min(s, word[k].start)
        e = Math.max(e, word[k].end)
      }
      out.push([found[0], s, e])
      start = found[1]
    }
    return out
  }
}
